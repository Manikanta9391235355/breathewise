"""
Pydantic data models and schemas for EstateIQ AI API.
Defines strict request/response validation and serialization.
"""

from typing import Any, Optional
from pydantic import BaseModel, Field


class ChatMessage(BaseModel):
    role: str = Field(..., description="Message role: 'user' or 'assistant'")
    content: str = Field(..., description="Message text content")


class ChatRequest(BaseModel):
    question: str = Field(..., min_length=2, max_length=1000, description="User's real estate query")
    source_filter: Optional[str] = Field("all", description="Source filter: 'all', 'DarGlobal', or 'Wasalt'")
    conversation_history: Optional[list[ChatMessage]] = Field(default=None, description="Previous session turns")


class Citation(BaseModel):
    source: str = Field(..., description="Source platform name: DarGlobal or Wasalt")
    title: str = Field(..., description="Property or project title")
    location: str = Field(..., description="City and country location")
    price: str = Field(..., description="Published price or guidance")
    url: str = Field(..., description="Original clickable website URL")
    snippet: str = Field(..., description="Exemplar excerpt supporting the answer")
    similarity_score: float = Field(..., description="FAISS cosine similarity score")


class ChatResponse(BaseModel):
    answer: str = Field(..., description="Grounded answer generated by OpenRouter model")
    citations: list[Citation] = Field(default_factory=list, description="Verifiable source citations")
    model: str = Field(..., description="LLM model identifier used for inference")
    chunks_used: int = Field(..., description="Number of evidence chunks retrieved and provided to LLM")
    status: str = Field(..., description="Response status: 'success', 'insufficient_evidence', 'error', etc.")
    source_filter: str = Field(..., description="Applied source filter")
    error: Optional[str] = Field(default=None, description="Detailed error information if applicable")


class PropertyItem(BaseModel):
    id: str = Field(..., description="Unique property identifier")
    name: str = Field(..., description="Project or property title")
    project_code: Optional[str] = Field(default="", description="Project code if available")
    source: str = Field(..., description="Platform: DarGlobal or Wasalt")
    property_type: str = Field(..., description="Villa, Apartment, Penthouse, etc.")
    country: str = Field(..., description="Country")
    city: str = Field(..., description="City or district")
    location: str = Field(..., description="Full address / location string")
    developer: str = Field(..., description="Developer or listing agency")
    description: str = Field(..., description="Detailed project description")
    amenities: list[str] = Field(default_factory=list, description="List of amenities")
    specifications: dict[str, Any] = Field(default_factory=dict, description="Specifications")
    price: str = Field(..., description="Formatted price string")
    currency: str = Field(..., description="Currency code (USD, SAR, etc.)")
    source_url: str = Field(..., description="Direct link to original webpage")
    scraped_at: str = Field(..., description="Collection timestamp ISO string")


class PaginatedProperties(BaseModel):
    items: list[PropertyItem] = Field(default_factory=list)
    total: int = Field(..., description="Total matching items count")
    page: int = Field(..., description="Current page number (1-based)")
    page_size: int = Field(..., description="Items per page")
    total_pages: int = Field(..., description="Total available pages")


class CollectionStats(BaseModel):
    total_properties: int = Field(..., description="Total indexed property records")
    darglobal_count: int = Field(..., description="DarGlobal developments count")
    wasalt_count: int = Field(..., description="Wasalt properties count")
    total_chunks: int = Field(..., description="Total RAG chunks in FAISS index")
    last_updated: str = Field(..., description="Timestamp of latest scrape")
    faiss_ready: bool = Field(..., description="Whether vector index is operational")
    available_countries: list[str] = Field(default_factory=list)
    available_property_types: list[str] = Field(default_factory=list)


class SourceDetail(BaseModel):
    name: str = Field(...)
    domain: str = Field(...)
    status: str = Field(...)
    indexed_items: int = Field(...)
    attempted_urls: int = Field(...)
    failed_urls: int = Field(...)
    last_collection: str = Field(...)
    description: str = Field(...)
    features: list[str] = Field(default_factory=list)


class SourcesResponse(BaseModel):
    sources: list[SourceDetail] = Field(default_factory=list)
    collection_report: dict[str, Any] = Field(default_factory=dict)


class ModelStatusResponse(BaseModel):
    model_name: str = Field(...)
    base_url: str = Field(...)
    is_configured: bool = Field(..., description="True if OPENROUTER_API_KEY is present")
    status: str = Field(..., description="'ready' or 'unconfigured'")
    free_tier_verified: bool = Field(default=True)


class HealthResponse(BaseModel):
    status: str = Field(..., description="'healthy' or 'degraded'")
    timestamp: str = Field(...)
    index_ready: bool = Field(...)
    total_chunks: int = Field(...)
    model_configured: bool = Field(...)
    app_version: str = Field(...)
